# A minimal Toybox.Graphics.Dc

class Dc:
    def __init__(self):
        self.img = Image.new("RGBA", (W * SS, W * SS), (0, 0, 0, 255))
        self.d = ImageDraw.Draw(self.img)
        self.fg = WHITE
        self.pen = 1

    def getWidth(self):
        return W

    def getHeight(self):
        return W

    def setColor(self, fg, bg=None):
        self.fg = fg

    def setPenWidth(self, w):
        self.pen = max(1, int(w))

    def clear(self):
        self.d.rectangle((0, 0, W * SS, W * SS), fill=(0, 0, 0, 255))

    def _ring_box(self, cx, cy, r):
        R = (r + self.pen / 2) * SS               # the watch centres the pen on the radius
        return (cx * SS - R, cy * SS - R, cx * SS + R, cy * SS + R)

    def drawCircle(self, cx, cy, r):
        self.d.ellipse(self._ring_box(cx, cy, r), outline=rgb(self.fg), width=self.pen * SS)

    def drawArc(self, cx, cy, r, direction, start, end):
        # clockwise from `start` to `end`, CIQ degrees (CCW from 3 o'clock); PIL goes clockwise from 3 o'clock
        self.d.arc(self._ring_box(cx, cy, r), -start, -end, fill=rgb(self.fg), width=self.pen * SS)

    def fillCircle(self, x, y, r):
        self.d.ellipse(((x - r) * SS, (y - r) * SS, (x + r) * SS, (y + r) * SS), fill=rgb(self.fg))

    def fillPolygon(self, pts):
        self.d.polygon([(x * SS, y * SS) for x, y in pts], fill=rgb(self.fg))

    def drawLine(self, x0, y0, x1, y1):
        self.d.line((x0 * SS, y0 * SS, x1 * SS, y1 * SS), fill=rgb(self.fg), width=self.pen * SS)

    def fillRectangle(self, x, y, w, h):
        self.d.rectangle((x * SS, y * SS, (x + w) * SS - 1, (y + h) * SS - 1), fill=rgb(self.fg))

    def drawRectangle(self, x, y, w, h):
        self.d.rectangle((x * SS, y * SS, (x + w) * SS - 1, (y + h) * SS - 1), outline=rgb(self.fg), width=self.pen * SS)

    def drawText(self, x, y, font, s):
        """Always TEXT_JUSTIFY_CENTER | TEXT_JUSTIFY_VCENTER, which is all the styles use."""
        if isinstance(font, SystemFont):
            self.d.text((x * SS, y * SS), s, font=font.f, fill=rgb(self.fg), anchor="mm")
            return
        x0 = x - font.width(s) / 2
        y0 = y - font.height() / 2
        tint = Image.new("RGBA", font.page.size, rgb(self.fg))
        for ch in s:
            c = font.chars.get(ord(ch))
            if c is None:
                continue
            if c["width"] > 0 and c["height"] > 0:
                box = (c["x"], c["y"], c["x"] + c["width"], c["y"] + c["height"])
                alpha = font.page.crop(box).split()[3]
                g = tint.crop(box)
                g.putalpha(alpha)
                g = g.resize((c["width"] * SS, c["height"] * SS), Image.LANCZOS)
                self.img.alpha_composite(g, (int((x0 + c["xoffset"]) * SS), int((y0 + c["yoffset"]) * SS)))
            x0 += c["xadvance"]

    def drawRadialText(self, cx, cy, font, s, angle, r, clockwise):
        """Centred on `angle`, letters' middles on radius r; clockwise = along the top, upright."""
        total = font.f.getlength(s) / SS
        span = total / r
        a = math.radians(angle) + (span / 2 if clockwise else -span / 2)
        size = int(font.f.size * 2)
        for ch in s:
            w = font.f.getlength(ch) / SS
            da = w / r
            mid = a - da / 2 if clockwise else a + da / 2
            g = Image.new("RGBA", (size, size), (0, 0, 0, 0))
            ImageDraw.Draw(g).text((size / 2, size / 2), ch, font=font.f, fill=rgb(self.fg), anchor="mm")
            rot = math.degrees(mid) - 90 if clockwise else math.degrees(mid) + 90
            g = g.rotate(rot, resample=Image.BICUBIC, center=(size / 2, size / 2))
            px, py = (cx + r * math.cos(mid)) * SS, (cy - r * math.sin(mid)) * SS
            self.img.alpha_composite(g, (int(px - size / 2), int(py - size / 2)))
            a = a - da if clockwise else a + da

    def result(self):
        out = self.img.resize((W, W), Image.LANCZOS).convert("RGB")
        mask = Image.new("L", (W, W), 0)
        ImageDraw.Draw(mask).ellipse((0, 0, W - 1, W - 1), fill=255)
        black = Image.new("RGB", (W, W), (0, 0, 0))
        return Image.composite(out, black, mask)


