#!/usr/bin/env python3
"""Store screenshots of the main screen in each style, rendered from a Python port of the styles'
drawing code (source/styles/*.mc) with the app's own bitmap fonts (resources/fonts/).

Usage: screens.py OUT_DIR [TASK_TITLE]
    -> OUT_DIR/screen_<n>_<name>.png (390x390, Forerunner 165 size): one per style, plus the
       statistics screen. With TASK_TITLE, the styles show it as the task being worked on.

This is not the simulator: two kinds of text use stand-ins. The watch's system fonts (FONT_XTINY,
FONT_SMALL: Roboto) and the curved labels (vector RobotoCondensedBold) are drawn with Noto Sans, which is close.
Keep this port in step with the .mc files when a style changes.
"""
import math, os, re, sys
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = sys.argv[1]
W = 390
SS = 3                      # supersampling, like the watch's anti-aliasing
NOTO = "/usr/share/fonts/noto"

FOCUS, SHORT, LONG, GOAL, DIM, TRACK = 0xFF5544, 0x44DD88, 0x44AAFF, 0xFFB000, 0x8A8A8A, 0x2A2A2A
WHITE, BLACK = 0xFFFFFF, 0x000000
IDLE, FOCUS_PH, SHORT_BREAK, LONG_BREAK = 0, 1, 2, 3


def shade(c, f):
    return (int(((c >> 16) & 0xFF) * f) << 16) | (int(((c >> 8) & 0xFF) * f) << 8) | int((c & 0xFF) * f)


def rgb(c):
    return ((c >> 16) & 0xFF, (c >> 8) & 0xFF, c & 0xFF, 255)


# ---------------------------------------------------------------------------
# Fonts

class BitmapFont:
    """BMFont text format (.fnt + one .png page), as generated by tools/make_font.py."""

    def __init__(self, name):
        path = f"{ROOT}/resources/fonts/{name}.fnt"
        self.chars = {}
        for line in open(path):
            kv = dict(re.findall(r'(\w+)=("[^"]*"|\S+)', line))
            if line.startswith("common"):
                self.line_h = int(kv["lineHeight"])
            elif line.startswith("page"):
                self.page = Image.open(f"{ROOT}/resources/fonts/{kv['file'].strip(chr(34))}").convert("RGBA")
            elif line.startswith("char "):
                self.chars[int(kv["id"])] = {k: int(v) for k, v in kv.items()}

    def width(self, s):
        return sum(self.chars[ord(c)]["xadvance"] for c in s if ord(c) in self.chars)

    def height(self):
        return self.line_h


class SystemFont:
    """Stand-in for a built-in font (Roboto on the FR165) or a vector font."""

    def __init__(self, path, px, line_h):
        self.f = ImageFont.truetype(path, px * SS)
        self.line_h = line_h

    def height(self):
        return self.line_h

    def width(self, s):
        return self.f.getlength(s) / SS


FONT_XTINY = SystemFont(f"{NOTO}/NotoSans-Regular.ttf", 22, 30)      # FR165: Roboto, 30 px line
FONT_SMALL = SystemFont(f"{NOTO}/NotoSans-Regular.ttf", 32, 45)      # FR165: Roboto, 45 px line
ARC_FONT = SystemFont(f"{NOTO}/NotoSans-CondensedBold.ttf", 20, 24)   # getVectorFont RobotoCondensedBold 19


