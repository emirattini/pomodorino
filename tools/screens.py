# Frame and the shared helpers (Styles.mc, Theme.mc)

class Frame:
    def __init__(self, **kw):
        self.phase, self.running, self.paused = FOCUS_PH, True, False
        self.frac, self.minutes = 0.4, 25
        self.today, self.goal, self.streak = 5, 8, 3
        self.cycle, self.every, self.tick = 1, 4, 0
        self.clock = "14:25"
        self.task = None
        self.__dict__.update(kw)
        total = self.minutes * 60
        self.rem = int(round(total * (1 - self.frac)))
        self.color = {SHORT_BREAK: SHORT, LONG_BREAK: LONG}.get(self.phase, FOCUS)


def phase_name(ph):
    return {FOCUS_PH: "FOCUS", SHORT_BREAK: "SHORT BREAK", LONG_BREAK: "LONG BREAK"}.get(ph, "POMODORINO")


def phase_title(ph):
    return {FOCUS_PH: "Focus", SHORT_BREAK: "Short break", LONG_BREAK: "Long break"}.get(ph, "Pomodorino")


def spaced(s):
    return " ".join(s)


def fmt(sec):
    return f"{sec // 60:02d}:{sec % 60:02d}"


def status(f):
    if f.running:
        return "UNTIL " + f.clock
    return "PAUSED" if f.paused else "PRESS START"


def px(cx, r, deg):
    return cx + r * math.cos(math.radians(deg))


def py(cy, r, deg):
    return cy - r * math.sin(math.radians(deg))


def arc_cw(dc, cx, cy, r, start, sweep):
    if sweep >= 359.9:
        dc.drawCircle(cx, cy, r)
    elif sweep > 0.3:
        dc.drawArc(cx, cy, r, "cw", start, start - sweep)


def goal_segments(dc, cx, cy, r, pen, count, goal):
    n = max(1, goal)
    dark = shade(GOAL, 0.22)
    dc.setPenWidth(pen)
    span = 360.0 / n
    gap = 4.0 if n <= 12 else 2.5
    for i in range(n):
        start = 90 - i * span - gap / 2
        dc.setColor(GOAL if i < count else dark)
        dc.drawArc(cx, cy, r, "cw", start, start - (span - gap))


def arc_label(dc, cx, cy, r, text, color, top):
    dc.setColor(color)
    dc.drawRadialText(cx, cy, ARC_FONT, text, 90 if top else 270, r, top)


def text(dc, x, y, font, s, color):
    dc.setColor(color)
    dc.drawText(x, y, font, s)


def chord(y, r):
    dy = abs(y - W / 2)
    return int(2 * math.sqrt(r * r - dy * dy)) - 12 if dy < r else 0


def fit(font, s, max_w):
    if font.width(s) <= max_w:
        return s
    n = len(s) - 1
    while n > 1 and font.width(s[:n] + "…") > max_w:
        n -= 1
    return s[:n] + "…"


def wrap(s, w1, w2):
    """Draw.wrap: balanced lines if the title fits on two, else whole words on line 1 and "…" on line 2."""
    font = FONT_XTINY
    if font.width(s) <= w1:
        return [s]
    fits1 = [i for i in range(1, len(s) - 1) if s[i] == " " and font.width(s[:i]) <= w1]
    if not fits1:
        return [fit(font, s, w1)]
    both = [i for i in fits1 if font.width(s[i + 1:]) <= w2]
    if both:
        cut = min(both, key=lambda i: max(font.width(s[:i]) / w1, font.width(s[i + 1:]) / w2))
    else:
        cut = max(fits1)
    return [s[:cut], fit(font, s[cut + 1:], w2)]


def status_line(dc, cx, y, r, font, st, color, f):
    """Draw.statusLine: the task title (one or two lines) replaces the status. Returns the extra height."""
    if f.task is None or f.paused:
        text(dc, cx, y, font, st, color)
        return 0
    lh = int(FONT_XTINY.height() * 0.85)
    lines = wrap(f.task, chord(y, r), chord(y + lh, r))
    text(dc, cx, y, FONT_XTINY, lines[0], 0xCCCCCC)
    if len(lines) < 2:
        return 0
    text(dc, cx, y + lh, FONT_XTINY, lines[1], 0xCCCCCC)
    return lh


def today_text(f):
    s = f"{f.today} / {f.goal} TODAY"
    if f.streak > 0:
        s += f"  ·  {f.streak} DAY STREAK"
    return s


