def ember(dc, f):
    timer = BitmapFont("timer_ember")
    cx = cy = W // 2
    s = 1.0
    goal_segments(dc, cx, cy, cx - 8, 7, f.today, f.goal)
    # drawSession
    r, pen, color = cx - 58, 14, f.color
    bright = 1.0 if f.running else 0.55
    dc.setPenWidth(pen)
    dc.setColor(shade(color, 0.16))
    dc.drawCircle(cx, cy, r)
    if f.frac > 0:
        sweep = 360.0 * f.frac
        dc.setPenWidth(pen + (10 * cx // 195))
        dc.setColor(shade(color, 0.14 * bright))
        arc_cw(dc, cx, cy, r, 90, sweep)
        dc.setPenWidth(pen)
        steps = int(f.frac * 60) + 1
        for i in range(steps):
            a0 = 90 - sweep * i / steps
            a1 = 90 - sweep * (i + 1) / steps - 0.8
            dc.setColor(shade(color, (0.3 + 0.7 * (i + 1) / steps) * bright))
            dc.drawArc(cx, cy, r, "cw", a0, a1)
        dc.setColor(shade(color, 0.3 * bright))
        dc.fillCircle(cx, cy - r, pen // 2)
        tx, ty = px(cx, r, 90 - sweep), py(cy, r, 90 - sweep)
        halo = 7 if (f.running and f.tick % 2 == 0) else 4
        dc.setColor(shade(color, 0.4 * bright))
        dc.fillCircle(tx, ty, pen // 2 + halo)
        dc.setColor(shade(color, bright))
        dc.fillCircle(tx, ty, pen // 2 + 1)
        dc.setColor(WHITE if f.running else DIM)
        dc.fillCircle(tx, ty, pen // 4)
    rt = cx - 33
    arc_label(dc, cx, cy, rt, spaced(phase_name(f.phase)), f.color, True)
    arc_label(dc, cx, cy, rt, today_text(f), GOAL if f.today >= f.goal else shade(GOAL, 0.8), False)
    # drawPips
    y, gap, rr = cy - 50, 22, 5
    x0 = cx - (f.every - 1) * gap // 2
    for i in range(f.every):
        x = x0 + i * gap
        if i < f.cycle:
            dc.setColor(shade(FOCUS, 0.35)); dc.fillCircle(x, y, rr + 3)
            dc.setColor(FOCUS); dc.fillCircle(x, y, rr)
        elif i == f.cycle and f.phase == FOCUS_PH:
            dc.setColor(FOCUS); dc.setPenWidth(2); dc.drawCircle(x, y, rr + 1)
            if f.running:
                dc.fillCircle(x, y, rr // 2)
        else:
            dc.setColor(shade(DIM, 0.6)); dc.setPenWidth(2); dc.drawCircle(x, y, rr)
    text(dc, cx, cy, timer, fmt(f.rem), WHITE if f.running or f.phase == IDLE else DIM)
    status_line(dc, cx, cy + 50, cx - 71, FONT_XTINY, status(f), f.color if f.paused else DIM, f)


def drain(dc, f):
    timer, label = BitmapFont("timer_drain"), BitmapFont("label_drain")
    cx = cy = W // 2
    col = f.color if (f.running or f.phase == IDLE) else shade(f.color, 0.55)
    rG = cx - 9
    dc.setPenWidth(3)
    dc.setColor(shade(GOAL, 0.2))
    dc.drawCircle(cx, cy, rG)
    gf = min(1.0, f.today / f.goal if f.goal > 0 else 0.0)
    if gf > 0:
        dc.setColor(GOAL)
        arc_cw(dc, cx, cy, rG, 90, 360 * gf)
        dc.fillCircle(px(cx, rG, 90 - 360 * gf), py(cy, rG, 90 - 360 * gf), 5)
    rS, pen = cx - 46, 26
    dc.setPenWidth(pen)
    dc.setColor(shade(col, 0.1))
    dc.drawCircle(cx, cy, rS)
    left = 1.0 - f.frac
    if left > 0.002:
        start = 90 - 360 * f.frac
        dc.setColor(col)
        arc_cw(dc, cx, cy, rS, start, 360 * left)
        dc.fillCircle(px(cx, rS, start), py(cy, rS, start), pen // 2)
        dc.fillCircle(cx, cy - rS, pen // 2)
    text(dc, cx, cy - 58, label, phase_name(f.phase), col)
    text(dc, cx, cy + 4, timer, fmt(f.rem), WHITE if f.running or f.phase == IDLE else DIM)
    text(dc, cx, cy + 60, label, f"{f.today} / {f.goal} TODAY", GOAL)
    status_line(dc, cx, cy + 90, cx - 65, label, status(f), col if f.paused else DIM, f)


def mono(dc, f):
    timer, label = BitmapFont("timer_mono"), BitmapFont("label_mono")
    cx = cy = W // 2
    col = shade(f.color, 0.55) if f.paused else f.color
    rS = cx - 40
    dc.setPenWidth(2)
    dc.setColor(0x333333)
    dc.drawCircle(cx, cy, rS)
    dc.setColor(0x555555)
    t = 8
    for a in range(0, 360, 90):
        dc.drawLine(px(cx, rS - t, a), py(cy, rS - t, a), px(cx, rS + t, a), py(cy, rS + t, a))
    dc.setPenWidth(4)
    dc.setColor(col)
    arc_cw(dc, cx, cy, rS, 90, 360 * f.frac)
    kx, ky = px(cx, rS, 90 - 360 * f.frac), py(cy, rS, 90 - 360 * f.frac)
    dc.fillCircle(kx, ky, 12)
    dc.setColor(BLACK)
    dc.fillCircle(kx, ky, 5)
    cursor = "_" if (f.running and f.tick % 2 == 0) else " "
    text(dc, cx, cy - 60, label, "// " + phase_name(f.phase).lower() + cursor, col)
    text(dc, cx, cy, timer, fmt(f.rem), WHITE if f.running or f.phase == IDLE else DIM)
    st = "ends " + f.clock if f.running else ("paused" if f.paused else "press start")
    below = status_line(dc, cx, cy + 44, cx - 50, label, st, DIM, f)
    big = f.goal > 10
    sq, pitch = (7, 10) if big else (10, 16)
    per_row = 15 if big else f.goal
    y0 = cy + 70 + below
    for i in range(f.goal):
        row = i // per_row
        in_row = f.goal - row * per_row if row == (f.goal - 1) // per_row else per_row
        x = cx - (in_row * pitch - (pitch - sq)) // 2 + (i % per_row) * pitch
        y = y0 + row * pitch
        if i < f.today:
            dc.setColor(GOAL); dc.fillRectangle(x, y, sq, sq)
        else:
            dc.setColor(0x555555); dc.setPenWidth(1); dc.drawRectangle(x, y, sq, sq)
    rows = (f.goal + per_row - 1) // per_row
    text(dc, cx, y0 + rows * pitch + 14, label, f"set={f.cycle}/{f.every}  streak={f.streak}", DIM)


def liquid(dc, f):
    timer, small = BitmapFont("timer_liquid"), BitmapFont("small_liquid")
    cx = cy = W // 2
    col = f.color if (f.running or f.phase == IDLE) else shade(f.color, 0.6)
    goal_segments(dc, cx, cy, cx - 8, 6, f.today, f.goal)
    rS = cx - 54

    def wave(r, frac, amp, phase, color):
        n = 18
        level = cy + r - 2 * r * frac
        top, bottom = [], []
        for i in range(n + 1):
            dx = -r + 2.0 * r * i / n
            half = math.sqrt(max(0.0, r * r - dx * dx))
            y = level + amp * math.sin(2 * math.pi * (dx / (r * 1.2) + phase))
            y = min(max(y, cy - half), cy + half)
            top.append((cx + dx, y))
            bottom.append((cx + dx, cy + half))
        dc.setColor(color)
        dc.fillPolygon(top + bottom[::-1])

    if f.frac > 0:
        t = (f.tick % 4) / 4.0
        wave(rS - 4, f.frac, 7, t + 0.5, shade(col, 0.22))
        wave(rS - 4, f.frac, 6, t, shade(col, 0.5))
    dc.setPenWidth(3)
    dc.setColor(shade(col, 0.7))
    dc.drawCircle(cx, cy, rS)
    rt = cx - 33
    arc_label(dc, cx, cy, rt, spaced(phase_name(f.phase)), col, True)
    arc_label(dc, cx, cy, rt, today_text(f), GOAL if f.today >= f.goal else shade(GOAL, 0.8), False)
    text(dc, cx, cy, timer, fmt(f.rem), WHITE if f.running or f.phase == IDLE else 0xBBBBBB)
    status_line(dc, cx, cy + 52, cx - 61, small, status(f), 0xDDDDDD, f)


def classic(dc, f):
    TOMATO, CREAM, SAGE, SKY = 0xE4573D, 0xF4E9D8, 0x8FB996, 0x7FA7C9
    timer, label, small = BitmapFont("timer_classic"), BitmapFont("label_classic"), BitmapFont("small_classic")
    cx = cy = W // 2
    pcol = SAGE if f.phase == SHORT_BREAK else (SKY if f.phase == LONG_BREAK else TOMATO)
    rS = cx - 46
    n = min(60, max(5, f.minutes))
    lit = int(f.frac * n)
    for i in range(n):
        a = 90 - i * 360.0 / n
        x, y = px(cx, rS, a), py(cy, rS, a)
        if i < lit:
            dc.setColor(pcol); dc.fillCircle(x, y, 5)
        elif i == lit and f.running:
            dc.setColor(shade(pcol, 0.35)); dc.fillCircle(x, y, 9 if f.tick % 2 == 0 else 7)
            dc.setColor(CREAM); dc.fillCircle(x, y, 5)
        else:
            dc.setColor(0x4A4038); dc.fillCircle(x, y, 3)
    # drawTomatoes
    sm = f.goal > 12
    step = 132.0 / (f.goal - 1) if sm else 11.0
    r = 5 if sm else 7
    l = r * 5 // 7
    rr = cx - 16
    for i in range(f.goal):
        a = 270 + (i - (f.goal - 1) / 2.0) * step
        x, y = px(cx, rr, a), py(cy, rr, a)
        done = i < f.today
        dc.setColor(TOMATO if done else 0x3A2E28)
        dc.fillCircle(x, y, r)
        dc.setColor(SAGE if done else 0x2E3A30)
        dc.fillPolygon([(x - l, y - r + 1), (x, y - r + 3 * l / 5), (x + l, y - r + 1), (x, y - r - 2 * l / 5)])
    text(dc, cx, cy - 62, label, "Paused" if f.paused else phase_title(f.phase), pcol)
    text(dc, cx, cy + 2, timer, fmt(f.rem), CREAM if f.running or f.phase == IDLE else shade(CREAM, 0.55))
    stats = f"{f.today} of {f.goal} today"
    if f.streak > 0:
        stats += f"  ·  {f.streak} day streak"
    text(dc, cx, cy + 62, small, stats, shade(CREAM, 0.7))
    st = "until " + f.clock if f.running else ("" if f.paused else "press start")
    status_line(dc, cx, cy + 88, cx - 55, small, st, shade(CREAM, 0.45), f)


def stats(dc, f):
    """Port of StatsView.onUpdate. f.days: the last 7 days as (count, goal, day letter), oldest first."""
    cx = cy = W // 2
    s = W / 416.0
    goal, days = f.goal, f.days
    text(dc, cx, cy - int(150 * s), FONT_XTINY, "LAST 7 DAYS", DIM)
    max_v = max([goal] + [d[0] for d in days]) or 1
    week = sum(d[0] for d in days)
    chart_w, max_h = int(290 * s), int(150 * s)
    base, bar_w = cy + int(55 * s), int(28 * s)
    step = (chart_w - bar_w) // 6
    left = cx - chart_w // 2
    xh = FONT_XTINY.height()
    for i, (count, day_goal, letter) in enumerate(days):
        x = left + i * step
